<?php

namespace App\Modules\AiBridge\Console;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Process;
use Symfony\Component\Process\ExecutableFinder;

/**
 * Writes contracts/db/schema.sql (CT-17 §5): runs the migrations on an empty scratch database,
 * dumps the structure with mysqldump (keeps CHECK constraints and generated columns) and appends
 * the worker roles from database/grants/workers.sql. Nobody edits schema.sql by hand.
 */
class GenerateContractsSchema extends Command
{
    /**
     * @var string
     */
    protected $signature = 'atlantech:contracts-schema
        {--output= : Where to write schema.sql (default: the PortHub contracts/db folder above this app)}
        {--database=atlantech_schema : Scratch database, created, migrated and dropped again}';

    /**
     * @var string
     */
    protected $description = 'Generate contracts/db/schema.sql from the migrations (CT-17)';

    public function handle(): int
    {
        $output = (string) ($this->option('output') ?: base_path('../../contracts/db/schema.sql'));
        if (! is_dir(dirname($output))) {
            $this->error("Folder not found: {$this->displayPath(dirname($output))}. Run from the PortHub checkout or pass --output.");

            return self::FAILURE;
        }

        $scratch = (string) $this->option('database');
        $original = config('database.connections.mysql.database');

        try {
            DB::connection('mysql')->statement("CREATE DATABASE IF NOT EXISTS `{$scratch}` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci");
            $this->useDatabase($scratch);
            Artisan::call('migrate:fresh', ['--database' => 'mysql', '--force' => true]);
            $lastMigration = (string) DB::connection('mysql')->table('migrations')->orderByDesc('id')->value('migration');

            $dump = Process::env(['MYSQL_PWD' => (string) config('database.connections.mysql.password')])
                ->timeout(120)
                ->run($this->mysqldumpCommand($scratch));

            if ($dump->failed()) {
                $this->error('mysqldump failed: '.trim($dump->errorOutput()));

                return self::FAILURE;
            }

            file_put_contents($output, $this->header($lastMigration)
                .preg_replace('/ AUTO_INCREMENT=\d+/', '', str_replace("\r\n", "\n", $dump->output()))
                ."\n-- Worker roles (database/grants/workers.sql, DEC-08)\n\n"
                .str_replace("\r\n", "\n", file_get_contents(database_path('grants/workers.sql'))));
        } finally {
            DB::connection('mysql')->statement("DROP DATABASE IF EXISTS `{$scratch}`");
            $this->useDatabase($original);
        }

        $this->info("Wrote {$this->displayPath($output)} (last migration {$lastMigration}).");

        return self::SUCCESS;
    }

    /**
     * mysqldump on this machine when there is one (CI), otherwise the one in the docker-compose mysql service.
     *
     * @return list<string>
     */
    private function mysqldumpCommand(string $database): array
    {
        $flags = ['--no-data', '--skip-comments', '--skip-dump-date', '--set-gtid-purged=OFF', '--single-transaction', $database];
        $user = '--user='.config('database.connections.mysql.username');

        $local = (new ExecutableFinder)->find('mysqldump');
        if ($local !== null) {
            return [
                $local,
                '--host='.config('database.connections.mysql.host'),
                '--port='.config('database.connections.mysql.port'),
                $user,
                ...$flags,
            ];
        }

        return [
            'docker', 'compose', 'exec', '-T',
            '-e', 'MYSQL_PWD='.config('database.connections.mysql.password'),
            'mysql', 'mysqldump', $user, ...$flags,
        ];
    }

    private function header(string $lastMigration): string
    {
        preg_match('/^\| Status \| Approved (v[\d.]+)/m', (string) file_get_contents(base_path('docs/reference/split/contracts/CT-17.md')), $version);

        return '-- ATLANTECH port database schema (CT-17 '.($version[1] ?? 'unknown').").\n"
            ."-- Generated by `composer contracts:schema` from the project-backend migrations. Do not edit by hand.\n"
            ."-- Last migration: {$lastMigration}\n\n";
    }

    private function useDatabase(string $database): void
    {
        config(['database.connections.mysql.database' => $database]);
        DB::purge('mysql');
    }

    private function displayPath(string $path): string
    {
        return realpath($path) ?: $path;
    }
}
