<?php

namespace App\Modules\Access\Console;

use App\Modules\Access\Enums\Ability;
use App\Modules\Access\Enums\Role;
use App\Modules\Access\Services\RolePermissions;
use Illuminate\Console\Command;

/**
 * Generates PortHub contracts/role-matrix.md (P2-D1) from `Ability`, `Role` and `RolePermissions`, for Frontend (menus,
 * FE-022) and QA (FE-102). The file is never edited by hand: change the matrix in code, then run this command.
 */
class PublishRoleMatrix extends Command
{
    private const string VERSION = 'v1.0';

    /**
     * Add a line here, with a new VERSION, whenever the matrix changes.
     *
     * @var list<array{string, string, string}>
     */
    private const array CHANGE_LOG = [
        ['v1.0', '2026-11-03', 'First version: 12 roles, 27 abilities (P2-D1). `MARINE_SAFETY_OFFICER` and `storage.manage` wait for the Non-Container work.'],
    ];

    /**
     * @var string
     */
    protected $signature = 'atlantech:contracts-role-matrix
        {--output= : Where to write role-matrix.md (default: the PortHub contracts folder above this app)}';

    /**
     * @var string
     */
    protected $description = 'Generate contracts/role-matrix.md from the role-to-ability matrix (P2-D1)';

    public function handle(): int
    {
        $output = (string) ($this->option('output') ?: base_path('../../contracts/role-matrix.md'));

        if (! is_dir(dirname($output))) {
            $this->error('Folder not found: '.dirname($output).'. Run from the PortHub checkout or pass --output.');

            return self::FAILURE;
        }

        if (file_put_contents($output, $this->document()) === false) {
            $this->error("Could not write {$output}.");

            return self::FAILURE;
        }

        $this->info('Wrote '.(realpath($output) ?: $output).'.');

        return self::SUCCESS;
    }

    private function document(): string
    {
        $roles = Role::cases();
        $abilities = Ability::cases();

        $lines = [
            '# Role matrix',
            '',
            '| | |',
            '| --- | --- |',
            '| Version | '.self::VERSION.' |',
            '| Status | Draft: for review by Frontend and QA |',
            '| Owner | Backend Team |',
            '| Reviewers | Frontend Team (FE-021, FE-022), QA (FE-102) |',
            '| Source | `Ability`, `Role`, `RolePermissions` in the Backend (P2-D1) |',
            '',
            '> Generated by `composer contracts:role-matrix` from the Backend (`Ability`, `Role`, `RolePermissions`). Do not edit by hand: change the matrix in code and run the command again.',
            '',
            'Who may do what on the port API. A user holds one active role at a time (DEC-36). Every route declares the ability it needs; a role without it gets `403 FORBIDDEN`. There is no inheritance between roles: a Manager holds only the manager functions.',
            '',
            '## Ability by role',
            '',
            '| Ability | '.implode(' | ', array_map(fn (Role $role) => "`{$role->value}`", $roles)).' |',
            '| --- | '.implode(' | ', array_fill(0, count($roles), ':---:')).' |',
        ];

        foreach ($abilities as $ability) {
            $cells = array_map(fn (Role $role) => RolePermissions::allows($role, $ability) ? 'yes' : '', $roles);
            $lines[] = "| `{$ability->value}` | ".implode(' | ', $cells).' |';
        }

        $lines[] = '';
        $lines[] = '## Abilities of each role';
        $lines[] = '';

        foreach ($roles as $role) {
            $held = array_map(fn (Ability $ability) => "`{$ability->value}`", RolePermissions::abilitiesFor($role));
            $lines[] = "- `{$role->value}`: ".($held === [] ? 'none' : implode(', ', $held));
        }

        $terminalRoles = array_map(fn (Role $role) => "`{$role->value}`", array_filter($roles, fn (Role $role) => $role->isTerminalScoped()));
        $fieldRoles = array_map(fn (Role $role) => "`{$role->value}`", array_filter($roles, fn (Role $role) => $role->isFieldRole()));

        array_push(
            $lines,
            '',
            '## Rules that go with the matrix',
            '',
            '- **Open to every signed-in user:** `auth/me`, `auth/change-password`, `auth/logout` (and sign-in). A user with no active role gets 200 on these and 403 everywhere else.',
            '- **Terminal scope:** '.implode(', ', $terminalRoles).' act only on their own terminal. Another terminal\'s record answers `403 FORBIDDEN`, not 404. All other roles are port-wide.',
            '- **Field roles:** '.implode(', ', $fieldRoles).' hold only the own-task abilities (the supervisor also `terminal-status.update`) and no web ability: on the web they get 403 on everything else (DEC-48, P-20 "use the mobile app"). They reach only components assigned to them; another user\'s task answers `403 FORBIDDEN`.',
            '- **`MARINE_SAFETY_OFFICER`** holds no ability until the Non-Container work starts.',
            '- **Check order (FR-GL-01):** 401, then the password gate, then role and terminal scope (403), then the other checks.',
            '- **Terminal type** (equipment and yard for container terminals only) is checked by the endpoint, not by this matrix.',
            '- Every refused role, terminal or own-task check is audited as `REJECTED_ATTEMPT` (FR-GL-02).',
            '',
            '## Change log',
            '',
            '| Version | Date | Change |',
            '| --- | --- | --- |',
        );

        foreach (self::CHANGE_LOG as [$version, $date, $change]) {
            $lines[] = "| {$version} | {$date} | {$change} |";
        }

        $lines[] = '';

        return implode("\n", $lines);
    }
}
